"""
Quantizes the trained ReTINA model to full int8 TFLite, then emit a C byte
array (model.h) that can be compiled directly into the ESP-EYE firmware.

This step takes the model from ~100KB float32 down to roughly
20-30KB int8 and makes it fit the ESP-EYE or the ES32-CAM, whichever you're using.

Usage:
    python quantize_and_convert.py \
        --model tiny_resnet_obstacle.keras \
        --data_dir ./data \
        --out_dir ./esp_model
"""

import argparse
import os

import numpy as np
import tensorflow as tf

IMG_SIZE = 96


def representative_dataset_gen(data_dir, num_samples=200):
    """Yields real training images so the quantizer can calibrate activation
    ranges. Using diverse, representative images here matters a lot --
    a poor representative set is the most common cause of a quantized
    model that works in Python but performs badly on-device."""
    ds = tf.keras.utils.image_dataset_from_directory(
        os.path.join(data_dir, "train"),
        labels=None,
        color_mode="grayscale",
        image_size=(IMG_SIZE, IMG_SIZE),
        batch_size=1,
        shuffle=True,
    )
    count = 0
    for batch in ds:
        if count >= num_samples:
            break
        img = tf.cast(batch, tf.float32) / 255.0
        yield [img]
        count += 1


def quantize(model_path, data_dir, out_dir):
    os.makedirs(out_dir, exist_ok=True)

    model = tf.keras.models.load_model(model_path)

    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = lambda: representative_dataset_gen(data_dir)

    # Force full int8: input, output, and all ops. This is what TFLite Micro
    # on ESP32 expects -- mixed float/int8 graphs either fail to load or
    # fall back to slow float kernels for the unsupported ops.
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8

    tflite_model = converter.convert()

    tflite_path = os.path.join(out_dir, "tiny_resnet_obstacle_int8.tflite")
    with open(tflite_path, "wb") as f:
        f.write(tflite_model)

    size_kb = len(tflite_model) / 1024
    print(f"Quantized model written to {tflite_path} ({size_kb:.1f} KB)")

    if size_kb > 300:
        print("WARNING: model is larger than the ~250-300KB target budget. "
              "Consider narrowing channels further before flashing.")

    return tflite_model, tflite_path


def write_c_array(tflite_model, out_dir, var_name="g_model"):
    """Equivalent of `xxd -i model.tflite > model.h`, done in Python so the
    whole pipeline runs without a separate xxd dependency."""
    header_path = os.path.join(out_dir, "model.h")

    with open(header_path, "w") as f:
        f.write("// Auto-generated by quantize_and_convert.py -- do not edit by hand.\n")
        f.write("#ifndef TINY_RESNET_MODEL_H_\n#define TINY_RESNET_MODEL_H_\n\n")
        f.write("#include <cstdint>\n\n")
        f.write(f"alignas(8) const unsigned char {var_name}[] = {{\n")

        hex_bytes = [f"0x{b:02x}" for b in tflite_model]
        for i in range(0, len(hex_bytes), 12):
            f.write("  " + ", ".join(hex_bytes[i:i + 12]) + ",\n")

        f.write("};\n\n")
        f.write(f"const unsigned int {var_name}_len = {len(tflite_model)};\n\n")
        f.write("#endif  // TINY_RESNET_MODEL_H_\n")

    print(f"C array written to {header_path} ({len(tflite_model)} bytes, var name '{var_name}')")
    return header_path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", required=True, help="Path to trained .keras model")
    parser.add_argument("--data_dir", required=True, help="Path to data/ (uses train/ for calibration)")
    parser.add_argument("--out_dir", default="./esp_model")
    args = parser.parse_args()

    tflite_model, _ = quantize(args.model, args.data_dir, args.out_dir)
    write_c_array(tflite_model, args.out_dir)

    print("\nNext: copy model.h into the ESP-EYE firmware sketch directory "
          "and build esp_eye_firmware.ino.")


if __name__ == "__main__":
    main()